import { execFile } from "node:child_process";
import { promisify } from "node:util";

import { SHARE_PREVIEW_SECONDS, SHARE_PREVIEW_SIZE } from "../app/services/track-share-preview";

export async function encodeSharePreview(artwork: string, media: string, output: string) {
  const size = SHARE_PREVIEW_SIZE;
  await promisify(execFile)(
    "ffmpeg",
    [
      "-nostdin",
      "-hide_banner",
      "-loglevel",
      "error",
      "-filter_threads",
      "1",
      "-protocol_whitelist",
      "file,pipe",
      "-loop",
      "1",
      "-framerate",
      "25",
      "-i",
      artwork,
      "-protocol_whitelist",
      "file,pipe",
      "-i",
      media,
      "-map",
      "0:v:0",
      "-map",
      "1:a:0",
      "-map_metadata",
      "-1",
      "-map_chapters",
      "-1",
      "-vf",
      `scale=${size}:${size}:force_original_aspect_ratio=decrease,pad=${size}:${size}:(ow-iw)/2:(oh-ih)/2,setsar=1`,
      "-c:v",
      "libx264",
      "-threads",
      "2",
      "-pix_fmt",
      "yuv420p",
      "-preset",
      "fast",
      "-crf",
      "24",
      "-c:a",
      "aac",
      "-b:a",
      "160k",
      "-ar",
      "48000",
      "-ac",
      "2",
      "-shortest",
      "-t",
      String(SHARE_PREVIEW_SECONDS),
      "-movflags",
      "+faststart",
      output,
    ],
    { timeout: 120_000 },
  );
}
